"""统一黑话词源（单一事实源）。

旧架构里「短语改写表」和「评分器词表」是两套不相交的列表：短语表新收录的
黑话（拉齐颗粒度/组合拳/品效合一…）评分器不认识，于是改写产物里只要残留
这些词，评分器照样给 100 放行，出现「打地鼠」——每补一个黑话都得在两处
分别登记，漏一处就漏判。

本模块把每个黑话规则集中成一条 ``LexiconRule``，同时驱动两件事：
  1. **替换**：``pattern`` 命中 → ``replacement``（语法完整人话，可空仅用于
     删除句首过渡词），供短语改写引擎使用；
  2. **残留检测**：``residual``（核心黑话名词的纯字符串列表）用于评分——
     只要文本里还出现任一 residual，说明黑话没洗干净，评分器扣分、漏网的
     交给 LLM。

新增黑话只需在 ``RULES`` 加一条，替换与检测自动同时生效，杜绝两处脱节。

顺序约束：规则按列表顺序应用，长短语必须排在其包含的短词之前。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Tuple

# 空洞修饰前缀：整体吞掉，不让其变残留
M = r"(?:全方位|多维度|全链路|深度|全面|持续|进一步|大力|积极|有效|充分|强力|有力地?)"


@dataclass(frozen=True)
class LexiconRule:
    """一条黑话规则。

    pattern:     匹配黑话的正则（应用顺序 = 列表顺序，长短语在前）
    replacement: 替换文本；空串 = 删除（仅允许句首过渡词这类删除后不残句的）
    residual:    核心黑话名词（纯字符串，非正则）。文本中出现任一即判未洗净；
                 空列表 = 该规则只做替换、不参与残留检测（如正常措辞压缩）。
    """

    pattern: str
    replacement: str
    residual: Tuple[str, ...] = field(default_factory=tuple)



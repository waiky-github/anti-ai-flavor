def replacement_rules() -> List[Tuple[str, str]]:
    """返回 (pattern, replacement) 列表，供短语改写引擎按序应用。"""
    return [(r.pattern, r.replacement) for r in RULES]


def residual_keywords() -> List[str]:
    """汇总全部 residual 黑话名词（去重、保序），供评分器残留检测。"""
    seen: set = set()
    out: List[str] = []
    for r in RULES:
        for word in r.residual:
            if word not in seen:
                seen.add(word)
                out.append(word)
    return out

"""
patterns/p33_contrastive_negation.py — 对比否定（补 p01 的漏网）

## 背景（2026-10-26 修 bug）

``scoring._count_pattern_hits`` 里 p01 的正则是 ``不[仅只]?[^。]*?而[且却]``，
只覆盖「不仅…而且」「不只…而却」。而 p01 模块本身（``p01_not_x_but_y``）抓的是
「不是…而是」，**评分器从没调用过它**——所以正文里
「它没甩给我一句模棱两可的话，而是把猫拆成四栏挨个说」这种句子，
改写器会改，评分器却给 0 罚分。这是评分/改写两套规则漂移。

本 pattern 把「不是/没/并非 …，而是/都是/只是」统一收进来做检测。

## 不误伤的边界

只用逗号后的 **对比标记**（而是/都是/全是/只是/只有）判定。
「它不是医生，也替代不了医生」这类顺势并列不命中——那是正常免责声明。
"""

from ._extended import ExtendedPattern

PATTERN = ExtendedPattern(
    pattern_id="p33_contrastive_negation",
    description="对比否定：先否定再反转（不是X，而是Y / 没甩给我A，而是B），常见于 AI 强调句式",
    regexes=[
        r"(?:不是|并非|没有|没|不再|从不)[^。！？\n]{1,40}?[，,]\s*(?:而是|都是|全是|只是|只有)",
        r"(?:不是|并非)[^。！？\n，,]{1,30}?而是",
        # 2026-10-26 补漏：对偶否定——「不是所有的秃斑都可怕，也不是所有的掉毛都能等。」
        # 只认「不是所有/每……也不是所有/每」这个严格骨架，避免误伤
        # 「他不是不想去，也不是没时间」这类正常并列否定。
        r"(?:不是|并非)(?:所有|每)[^。！？\n]{1,25}?[，,]\s*也不是(?:所有|每)",
    ],
    penalty=3,
    scenes=("base",),
    note="对比否定（否定 + 反转强调）",
)

match = PATTERN.match

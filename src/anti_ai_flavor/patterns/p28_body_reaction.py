"""
patterns/p28_body_reaction.py — 身体反应修辞背书

## 现象

AI 想表现「我被打动了/我被说服了」，就写身体反应：
「看到这句我头皮麻了一下」「后背一凉」「心里咯噔一下」。
真人写感受会写**具体的事**（谁说了什么、当时在干什么），
不会把生理反应当成可信度背书。

## 判据

身体部位 + 瞬时生理反应动词，与「我/整个人/当场/瞬间」共存时命中。
"""

from ._extended import ExtendedPattern

PATTERN = ExtendedPattern(
    pattern_id="p28_body_reaction",
    description="身体反应修辞：用「头皮发麻/后背发凉/心里咯噔」代替具体感受，是 AI 装人的高频替代品",
    regexes=[
        # 身体部位 + 瞬时反应
        r"(?:我)?(?:头皮|后背|后颈|脊背|手心|心里|鼻子|眼眶|脸|血压|心跳|嗓子眼|汗毛|汗毛眼)"
        r"[^。！？\n]{0,8}?"
        r"(?:麻了一下|麻了|发麻|发凉|一凉|发紧|一紧|一沉|一酸|一软|咯噔|发烫|发热|发酸|发紧|"
        r"提到嗓子|揪起来|竖起来|凉了半截)",
        # 「整个人/当场/瞬间」+ 情绪动作
        r"(?:我)?(?:整个人|当场|瞬间|一下就)"
        r"[^。！？\n]{0,6}?"
        r"(?:麻了|僵住|愣住|绷不住|破防|坐起来|跳起来)",
    ],
    penalty=3,
    scenes=("base",),
    note="身体反应修辞（AI 用生理反应代替具体叙述）",
)

match = PATTERN.match

"""
patterns/p38_vague_elevation.py — 空洞升华 / 时代共振（2026-10-26 新增）

## 现象

AI 最爱用「时代」和「价值」把话题抬起来，具体信息为零：

  「在当今这个快节奏的时代，我们不仅要关注宠物的身体健康，更要关注它们的情绪价值。」
  「让我们一起来探索这个充满温度的话题。」
  「这件事值得我们深思。」

抽掉这些句子，事实一字不少——因为本来就没有事实。

## 判据（只收特征极强的骨架，避免误伤正常议论）

1. 在 (当今/这个/如今) … 时代 / 社会 / 背景下
2. 让我们 (一起) 探索 / 走进 / 聊聊 / 看看 / 了解
3. 情绪价值 / 充满温度 / 值得 (我们) 深思 / 思考 / 关注

真人写宠物会写「它今天没吃饭」「医生照了灯」这类可核验细节，
不会写「充满温度的话题」。
"""

from ._extended import ExtendedPattern

PATTERN = ExtendedPattern(
    pattern_id="p38_vague_elevation",
    description="空洞升华：时代/价值包装，抬话题不落细节（时代感开场、情绪价值、邀请探索、值得深思）",
    regexes=[
        r"在(?:当今|这个|如今)[^。！？\n]{0,20}(?:时代|社会|背景)",
        r"让我们(?:一起)?(?:来)?(?:探索|走进|聊聊|看看|了解|认识)",
        r"情绪价值|充满温度|充满温情",
        r"值得(?:我们)?(?:深思|思考|关注|期待)",
        # 2026-10-26 补漏（验收对抗样本实测漏检）：
        # 「它不只是掉毛，不只是皮屑，更是身体在向你发出求救信号」
        # 「这不仅仅是养宠，更是一种生活方式的全面升级」
        # 两类的共同骨架 = 递进否定 + 「更是」升华，且升华落到抽象名词不带事实。
        r"(?:不仅仅|不只是|不止是|不仅是|不光)[^。！？\n]{1,30}?[，,]\s*更是"
        r"(?:一种|一场|一次|一门|对|整个|一场场)",
        # 空洞成长：只有「成长/收获/受益」结论，没有「从X到Y」的事实
        r"(?:我|自己)?(?:成长了?很多|成长了不少|收获(?:了)?很多|受益匪浅|深有感触|感慨良多)"
        r"(?![^。！？\n]{0,20}(?:因为|具体|比如|从[^。！？\n]{1,10}到))",
    ],
    penalty=3,
    scenes=("base",),
    note="空洞升华（时代/价值包装，无具体事实）",
)

match = PATTERN.match

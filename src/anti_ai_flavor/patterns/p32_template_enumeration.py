"""
patterns/p32_template_enumeration.py — 模板化枚举

## 现象

AI 喜欢先把内容数出来再展开：「三件事」「四个字」「5 个坑」「A/B/C 三个选项」。
真人也会列清单，但清单项是**具体名词**；AI 的清单项常是同构的空壳，
而且序号形式高度模板化。

## 判据

数字 + 泛化量词（件事/个点/个坑/种情况/条建议…），以及 A/B/C 式编号、
「第 N 点：」式小标题。真实工程语境里的「三个维度」「两个核心场景」不命中。
"""

from ._extended import ExtendedPattern

PATTERN = ExtendedPattern(
    pattern_id="p32_template_enumeration",
    description="模板化枚举：先数再展开（三件事/四个字/5 个坑），清单常是同构空壳",
    regexes=[
        r"(?:[一二三四五六七八九十两]|\d)\s*"
        r"(?:件事|个点|个坑|个信号|种情况|句话|条建议|个方法|个细节|个习惯|个误区|个真相|步走|招搞定)",
        # A/B/C 式编号（大写字母 + 空格 + 中文）
        r"(?:^|[。！？\n])\s*[A-D]\s+[^。！？\n]{2,20}",
        # 「第 N 点：」
        r"第[一二三四五六七八九十\d]+(?:个|件|点|条|步)[：:，,]",
    ],
    penalty=2,
    # 2026-10-26：不进 base。技术文档里「双十一前做了三件事：①…②…③…」
    # 是正常人类结构（test_p23 已锁定该类文本必须 100 分）；「三件事」式
    # 枚举算不算 AI 味取决于场景，所以只在表达类/健康内容里生效。
    scenes=("social-note", "health-content"),
    note="模板化枚举（先数再展开）",
)

match = PATTERN.match

"""
patterns/p29_maxim_golden_line.py — 格言金句 / 对仗总结句

## 现象

AI 极爱在段尾给一句「可引用」的金句，结构是对仗或反转：

  「敢把『我不知道』写出来的，比什么都说满的可信。」
  「真正的好产品，从来不是靠功能堆出来的。」
  「越是急着解释，越说明有问题。」

这类句子的共同点是：**抽掉上下文也成立**，而且听起来很有道理。
真人叙事里，结论通常绑定具体的人和事（「他这么说完，我才敢问第二遍」）。

## 判据

四种可识别骨架：X 的，比 Y 更 Z / 越是 X 越 Y / 真正的 X 不是 Y / 敢把 X 写出来的，
"""

from ._extended import ExtendedPattern

PATTERN = ExtendedPattern(
    pattern_id="p29_maxim_golden_line",
    description="格言金句：段尾对仗/反转式结论，抽掉上下文仍成立，是 AI 收尾的典型手法",
    regexes=[
        # X 的，比 Y 更/都 Z
        r"[^。！？\n，,]{2,25}的[，,]\s*比[^。！？\n]{2,25}(?:更|还|都|要)?"
        r"(?:可靠|可信|重要|难得|值钱|珍贵|厉害|强|管用|有用)",
        # 越是 X 越 Y
        r"越是[^。！？\n]{2,20}[，,]\s*越[^。！？\n]{2,20}",
        # 真正的 X，从来不是 Y
        r"(?:真正|好的东西|真正好的)[^。！？\n]{0,12}[，,]\s*(?:从来|永远)?(?:不是|不在于|并不是)",
        # 敢把 X 写出来/承认的
        r"敢(?:把|承认|说|写)[^。！？\n]{1,20}(?:出来|承认|说出口)的",
        # 说到底是 X（2026-10-26 补漏：实测「养猫这件事，说到底，是一场关于耐心的修行」
        # 五种骨架全不命中——「说到底」是 AI 升华句的固定转场词）
        r"说到底[，,]\s*(?:是|就是|还是|不过是)",
        # 修辞化本质定义：是一场修行/旅程/艺术/哲学/态度
        r"(?:是|就是|不过是)(?:一场|一次|一门)?[^。！？\n]{0,12}(?:修行|旅程|艺术|哲学|智慧|浪漫)"
        r"|这(?:件事|一路|一切)[^。！？\n，,]{0,8}(?:修行|旅程|馈赠)",
    ],
    penalty=3,
    scenes=("base",),
    note="格言金句（可脱离上下文的对仗结论）",
)

match = PATTERN.match

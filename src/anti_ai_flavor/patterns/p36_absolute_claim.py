"""
patterns/p36_absolute_claim.py — 绝对化用语（全场景 base + health 加权）

## 现象

广告法禁用的绝对化表述：「最好的」「第一」「100%」「唯一」「必备」。

## 为什么不误伤

- 序数：「第一次」「第一步」「第一批」是序数，不是绝对化 → 排除。
- 数据库术语：「唯一索引」「唯一约束」→ 排除。
- 建议语气：「最好先问医生」是建议，不是宣称 → 只认「最好的/最好用/最好选」。
"""

from ._extended import ExtendedPattern

PATTERN = ExtendedPattern(
    pattern_id="p36_absolute_claim",
    description="绝对化用语：最好的/第一/100%/唯一/必备（排除序数与数据库术语、建议语气）",
    regexes=[
        r"最好(?:的|用|选)",
        # 序数不是绝对化。2026-11-03 用 78 篇真人技术文实测：命中「第一」
        # 的全是「第一个 token / 第一篇 / 第一轮 / 第一行 / 第一步 / 第一级
        # 目录 / 第一，当…」，原排除表缺 篇轮行级层种项段组列位条页张队人
        # 等序次量词，导致单篇最多被判 8 次。
        r"第一(?![次步眼天时批版个章节行轮阶段部分篇张条页组列位层种项段级队人方，、])",
        r"(?:100\s*%|百分之百)",
        # 技术文里「唯一」基本是数据属性或技术判断（唯一 ID / 唯一标识 /
        # 唯一约束 / 唯一组名称 / 全局唯一 / 唯一可行方案），2026-11-03 实测
        # 12 次命中里 11 次属于前者。改为只认吹嘘后缀（唯一能够 / 唯一可以 /
        # 唯一的选择），技术用法一律不命中。负向前瞻枚举不完（「唯一 ID」
        # 中间有空格就漏），正向断言更稳。
        r"唯一(?=\s*(?:能够|可以|能|真正|彻底|完全|满足|解决|正确|有效|值得|选择|出路|办法|途径))",
        r"(?:必备|必选|必买)",
    ],
    penalty=4,
    scenes=("base",),
    note="绝对化用语",
    min_occurrences=1,
)

match = PATTERN.match

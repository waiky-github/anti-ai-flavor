"""
patterns/p40_marketing_hype.py — 营销夸张腔（2026-10-26 新增）

## 背景（验收实测漏检）

``scripts/acceptance_scene_2026_10_26.py`` 的对抗样本

    「谁懂啊家人们！这个神器的出现，直接让养宠幸福感拉满！」

在 social-note 下 0 命中（100 分）。查过通道里所有既有 pattern：

  * 唯一沾边的是 ``p27_over_colloquial``（过度口语化），但它在社交场景被
    关掉——社媒就该口语，用它等于把正常人话判成 AI；
  * ``p36_absolute_claim`` 只抓「最好 / 第一 / 100% / 唯一 / 必备」这类
    绝对化用语，不抓「神器 / 拉满」这类**广告词**。

所以空出来的是「广告腔」这一层：不是绝对化，也不是口语化，而是把体验
包装成文案话术。

## 为什么这是 AI 味（在小红书语境）

真人分享猫癣会写「抹了快一个月才好」；写成「神器」「幸福感拉满」是
带货文案的语法。这类词在小红书里最容易被读者判定为「广告/机器人」，
也是平台判定软广的信号词。

## 不误伤的边界（重要）

  * 只认**商品化夸张**（神器、幸福感/体验感/满足感拉满、直接让…翻倍/起飞/封神），
    不认「谁懂啊家人们」——那是真人常用开场，拦住等于误杀正常社媒语域。
  * 不认单个「拉满」——「今天撸猫撸到手感拉满」是真人在说话。
  * 只在表达类 / 健康内容场景生效；技术文档里的「性能拉满」不归这里管。

## 处置

只判定不给 fix：删掉「神器」还剩什么取决于原话，机器替换会造出更假的句子。
"""

from ._extended import ExtendedPattern

PATTERN = ExtendedPattern(
    pattern_id="p40_marketing_hype",
    description="营销夸张腔：神器 / 幸福感拉满 / 直接让…翻倍起飞（带货文案语法）",
    regexes=[
        r"神器",
        r"(?:幸福感|体验感|满足感|优越感|高级感)[^。！？\n]{0,3}拉满",
        r"直接让[^。！？\n]{1,18}?(?:拉满|翻倍|起飞|封神|上(?:了)?一个台阶)",
        r"(?:撸猫|养宠|养猫)[^。！？\n]{0,6}(?:幸福感|体验感)[^。！？\n]{0,4}(?:拉满|爆棚)",
    ],
    penalty=3,
    scenes=("social-note", "health-content"),
    note="营销夸张腔（带货文案语法）",
)

match = PATTERN.match

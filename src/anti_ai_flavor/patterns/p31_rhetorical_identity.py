"""
patterns/p31_rhetorical_identity.py — 修辞身份铺垫

## 现象

AI 想建立权威时会先铺一层身份，再给断言：

  「作为一个在宠物行业做了十年的人，我必须说……」
  「我见过太多主人，一开始都不当回事。」

身份铺垫本身不是错，错在**它是修辞装置而不是信息来源**：去掉铺垫，
后面的判断一点没变；真人的身份通常是叙述里自然露出来的（「上次带它去的是
李医生，他照了灯」）。

## 判据

「作为 + 身份词 + 逗号 + 我/必须/建议」这类铺垫句，以及「我见过太多/无数」。
纯年资陈述（「我做了三年」）不命中，避免误伤简历。
"""

from ._extended import ExtendedPattern

PATTERN = ExtendedPattern(
    pattern_id="p31_rhetorical_identity",
    description="修辞身份铺垫：「作为一个做了十年的…，我必须说」——身份是修辞装置而非信息来源",
    regexes=[
        r"作为(?:一个|一名|一位|个|名)?[^。！？\n]{0,20}"
        r"(?:医生|兽医|护士|从业者|工程师|程序员|架构师|博主|过来人|宝妈|铲屎官|老手|内行)"
        r"[^。！？\n]{0,10}[，,][^。！？\n]{0,10}(?:我|必须|建议|想|真心)",
        r"我(?:见过|见)过(?:太多|无数|上百|上千)[^。！？\n]{0,12}",
    ],
    penalty=3,
    scenes=("base",),
    note="修辞身份铺垫（身份作为权威装置）",
)

match = PATTERN.match

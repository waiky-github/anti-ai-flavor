"""
patterns/p35_medical_claim.py — 医疗功效宣称（health-content 专属）

## 现象

宠物健康内容最容易踩的合规红线：把筛查/护理写成疗效。

  「这个功能能治猫藓」「三天消炎」「抗菌除螨」「有效缓解」

判据是**功效动词/词**：治疗、治愈、根治、消炎、抗菌、抗真菌、杀螨、
有效、见效、痊愈、除根治本。这些词在健康内容里出现即命中，
与上下文无关——因为监管看的是字面。

## 处置

penalty=10 且进 ``SceneProfile.compliance_patterns``：
命中后场景策略强制 ``block``，**不做自动改写**（合规类改写等于替用户
重写法律声明，风险转移给工具，不该做）。
"""

from ._extended import ExtendedPattern

PATTERN = ExtendedPattern(
    pattern_id="p35_medical_claim",
    description="医疗功效宣称：把筛查/护理写成疗效（治愈/根治/消炎/抗菌/有效…）",
    regexes=[
        r"(?:治疗|治愈|根治|除根|痊愈|特效|消炎|杀菌|抗菌|抗真菌|杀螨|除螨|驱螨)",
        # 「有效」单独命中会误杀普通文案（「有效提升效率」不是医疗宣称）。
        # 收紧为：功效词 + 医疗动作/结果，或 医疗对象 + 近距离功效词。
        r"(?:有效|见效|疗效|显效)(?:治疗|缓解|改善|抑制|杀灭|预防|祛除|去除|止痒|止血|退烧|调理|根治|控制)",
        r"(?:猫癣|猫藓|皮肤病|感染|炎症|发炎|螨|真菌|腹泻|呕吐|咳嗽|发烧|伤口|寄生虫)"
        r"[^。！？\n]{0,12}(?:有效|见效|痊愈|根治|治好)",
        r"(?:药到病除|立竿见影|一用就好|三天见效|一周搞定|几天就好)",
    ],
    penalty=10,
    scenes=("health-content",),
    note="医疗功效宣称（合规红线）",
)

match = PATTERN.match

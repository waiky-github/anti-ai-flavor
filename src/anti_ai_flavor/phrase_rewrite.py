"""短语级 AI 黑话改写（纯规则、0 token）。

与旧 Tier1「逐词删除、只删不补」不同，这里的操作单位是**短语**：
左边匹配一整段黑话固定搭配（含修饰词+动作+宾语），右边给一个**语法完整、
有动词有宾语**的人话短语，替换后句子依然成立。

设计约束：
  1. 长短语优先于短词（一次性整体替换，避免被短词先拆散）；
  2. 只做「替换」，不做「删除」——每条规则右侧都必须是非空完整短语；
  3. 匹配不到安全替换规则的词一律保留原词，绝不裸删（宁缺毋滥）；
  4. 受保护内容（代码/URL/版本/小数）在此之前已掩码，这里不会碰到。

主入口：``phrase_rewrite(text)``。
"""

from __future__ import annotations

import re
from typing import List, Tuple

# 空洞修饰前缀：整体吞掉，不让其变残留
_M = r"(?:全方位|多维度|全链路|深度|全面|持续|进一步|大力|积极|有效|充分|强力|有力地?)"


PHRASE_RULES: List[Tuple[str, str]] = [
    # —— 「赋能 … 闭环 / 生态」整段 ——
    (rf"{_M}*(?:赋能|助力){_M}*(?:核心)?业务闭环", "支撑核心业务"),
    (rf"{_M}*赋能(?:核心)?业务", "支撑业务"),
    (rf"{_M}*打造{_M}*(?:数智化|数字化|智能化){_M}*(?:新)?生态",
     "建设数智化平台"),
    (rf"{_M}*(?:打造|构建|建设){_M}*(?:新)?生态", "建设平台"),

    # —— 「夯实基座 / 提供支撑」 ——
    (rf"{_M}*夯实{_M}*(?:底层)?(?:基座|基础)", "稳固技术基础"),
    (r"为(?:核心)?(?:链路|业务)" + _M + r"*提供" + _M + r"*(?:战略)?支撑",
     "保障核心链路稳定"),
    (rf"{_M}*提供{_M}*(?:强有力的|战略)?支撑", "提供可靠保障"),
    # 兜底：残留的「(为…)提供…支撑」（含可能未被吞掉的副词）
    (r"为(?:核心)?(?:链路|业务)?提供.{0,8}?支撑", "提供可靠保障"),

    # —— 「助力 … 落地」 ——
    (rf"{_M}*(?:助力|推动){_M}*(?:业务)?价值最大化落地", "让业务产生实际收益"),
    (rf"{_M}*(?:助力|推动){_M}*落地", "推动落地"),

    # —— 会议/协作黑话 ——
    (r"拉通对齐", "对齐目标"),
    (r"拉齐", "对齐"),
    (r"对齐颗粒度", "统一下工作粒度"),
    (r"拉齐颗粒度", "统一下工作粒度"),
    (r"颗粒度(?:太|过)?(?:粗|细|大|小)", "工作粒度\1"),
    (r"对齐一下底层逻辑", "先理清基本思路"),
    (r"底层逻辑", "基本原理"),
    (r"主动拥抱变化", "适应变化"),
    (r"拥抱变化", "适应变化"),
    (r"通过组合拳打法", "用多种手段"),
    (r"打一套?组合拳", "采取多种措施"),
    (r"组合拳打法", "多种手段"),
    (r"组合拳", "多种措施"),
    (r"形成合力", "一起发力"),
    (r"真正做到品效合一", "兼顾品牌效果和实际转化"),
    (r"品效合一", "兼顾品牌效果和转化"),
    (r"把.{0,10}?形成闭环", "落实到位"),
    (r"形成可复用的方法论", "沉淀可复用的做法"),
    (r"可复用的方法论", "可复用的做法"),

    # —— 结尾 / 过渡短语 ——
    (r"总的来说[，,]?\s*", ""),
    (r"整体来看[，,]?\s*", ""),
    (r"综上所述[，,]?\s*", ""),

    # —— 轻度套路短语 ——
    (r"建议后续可以持续优化一下", "后续继续优化"),
    (r"会有进一步的?提升", "会有提升"),
    (r"避免出现明显的波动", "避免明显波动"),
    (r"避免出现的波动", "避免波动"),
]


# ---------------------------------------------------------------------------
# 受保护内容掩码
# ---------------------------------------------------------------------------

_FENCED = re.compile(r"```.*?```", re.DOTALL)
_INLINE = re.compile(r"`[^`\n]+`")
_URL = re.compile(
    r"(?:https?://|www\.)[^\s\u4e00-\u9fff\uff0c\u3002\uff01\uff1f\uff1b\uff1a"
    r"\u3001\uff08\uff09\u3010\u3011]+"
)
_EMAIL = re.compile(r"[A-Za-z0-9_.+-]+@[A-Za-z0-9-]+\.[A-Za-z0-9.-]+")
_PROTECT = (_FENCED, _INLINE, _URL, _EMAIL)


def _mask(text: str):
    saved: List[str] = []

    def _save(m):
        saved.append(m.group(0))
        return f"\x00{len(saved) - 1}\x00"

    for rx in _PROTECT:
        text = rx.sub(_save, text)
    return text, saved


def _unmask(text: str, saved: List[str]) -> str:
    return re.sub(
        r"\x00(\d+)\x00",
        lambda m: saved[int(m.group(1))],
        text,
    )


# ---------------------------------------------------------------------------
# 安全清理（不破坏语法）
# ---------------------------------------------------------------------------

_DUP_COMMA = re.compile(r"[,，]{2,}")
_DUP_SPACE = re.compile(r"[ \t]{2,}")
_ORPHAN_DE = re.compile(r"(全方位|多维度|深度|全面)的")


def _safe_cleanup(text: str) -> str:
    text = _DUP_COMMA.sub("，", text)
    text = _DUP_SPACE.sub(" ", text)
    text = _ORPHAN_DE.sub(r"\1", text)
    text = re.sub(r"\s+([，。！？；：）】」])", r"\1", text)
    return text.strip()


# ---------------------------------------------------------------------------
# 主入口
# ---------------------------------------------------------------------------

_COMPILED = [(re.compile(pat), repl) for pat, repl in PHRASE_RULES]


def phrase_rewrite(text: str) -> str:
    """短语级改写。只替换、不裸删；无规则的词保留；保护代码/URL。

    没有任何规则命中时原样返回（调用方据此判断是否需要走 LLM）。
    """
    if not text:
        return text
    masked, saved = _mask(text)
    s = masked
    changed = False
    for rx, repl in _COMPILED:
        new = rx.sub(repl, s)
        if new != s:
            changed = True
            s = new
    s = _safe_cleanup(s)
    out = _unmask(s, saved)
    return out if changed else text
